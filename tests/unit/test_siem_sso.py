        """
        Override session cookie domain/secure settings for test client.
        Production uses SESSION_COOKIE_DOMAIN=".cycentra.test" + SECURE=True.
        The test client sends plain HTTP to 'localhost', so the domain-scoped
        secure cookie is never included in requests — causing session.get("user_email")
        to return None.  Set domain=None and SECURE=False for this test class only.
        """
        orig = {
            "SESSION_COOKIE_DOMAIN": flask_app.config.get("SESSION_COOKIE_DOMAIN"),
            "SESSION_COOKIE_SECURE": flask_app.config.get("SESSION_COOKIE_SECURE"),
        }
        flask_app.config["SESSION_COOKIE_DOMAIN"] = None
        flask_app.config["SESSION_COOKIE_SECURE"] = False
