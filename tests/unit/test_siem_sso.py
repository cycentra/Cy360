class TestUserinfoForCySiem:
    """
    After the OIDC token exchange, oauth2-proxy calls /oidc/userinfo with the
    access_token to get the user's email for X-Auth-Request-Email.
    This endpoint must return the correct email so nginx can set X-Proxy-User.
    """

    def test_userinfo_returns_email_after_cysiem_token_exchange(self, client, flask_app):
        """
        Full flow: token exchange for oauth2proxy → userinfo returns email.
        This email becomes X-Auth-Request-Email → $proxy_user → X-Proxy-User
        header sent to Wazuh Dashboard.
        """
        from core.config import OIDC_CLIENTS
        secret   = OIDC_CLIENTS["oauth2proxy"]["client_secret"]
        code     = "test_userinfo_email_flow"
        email    = "analyst@siem-test.local"
        redirect = OIDC_CLIENTS["oauth2proxy"]["redirect_uris"][0]

        _seed_auth_code(flask_app, code, "oauth2proxy", email, redirect_uri=redirect)

        # Exchange code for tokens
        token_resp = client.post(
            "/oidc/token",
            data={
                "grant_type":    "authorization_code",
                "code":          code,
                "client_id":     "oauth2proxy",
                "client_secret": secret,
            },
        )
        assert token_resp.status_code == 200, \
            f"Token exchange failed: {token_resp.data}"
        access_token = json.loads(token_resp.data)["access_token"]

        # Fetch userinfo (as oauth2-proxy would, server-to-server, no browser cookie)
        info_resp = client.get(
            "/oidc/userinfo",
            headers={"Authorization": f"Bearer {access_token}"},
        )
        assert info_resp.status_code == 200, \
            f"Userinfo failed: {info_resp.data}"
        info = json.loads(info_resp.data)
        assert info.get("email") == email, (
            f"Userinfo email mismatch — X-Auth-Request-Email would be wrong: {info}"
        )
        assert info.get("sub") == email, f"sub mismatch: {info}"

    def test_userinfo_invalid_token_returns_401(self, client):
        """Expired/invalid access token must return 401 — not 500."""
        resp = client.get(
            "/oidc/userinfo",
            headers={"Authorization": "Bearer invalidtoken12345"},
        )
        assert resp.status_code == 401


