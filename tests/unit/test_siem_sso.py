def _basic_header(client_id: str, client_secret: str) -> str:
    raw = f"{client_id}:{client_secret}"
    return "Basic " + base64.b64encode(raw.encode()).decode()


def _seed_auth_code(flask_app, code: str, client_id: str, email: str,
                    redirect_uri: str = "https://cysoc.cycentra.test/oauth2/callback"):
    """Inject a valid auth code directly into the provider's in-memory store."""
    from blueprints.oidc import provider as oidc_prov
    oidc_prov._AUTH_CODES[code] = {
        "email":        email,
        "client_id":    client_id,
        "redirect_uri": redirect_uri,
        "nonce":        "test-nonce",
        "expires":      time.time() + 300,
    }


def _seed_rbac(flask_app, email: str, role: str):
    """Inject a user → role mapping for the test."""
    from blueprints.rbac import manager as rbac_mgr
    orig_fn = rbac_mgr._load_rbac

    def _fake_load():
        return {email: {"role": role}}

    rbac_mgr._load_rbac = _fake_load
    yield
    rbac_mgr._load_rbac = orig_fn


