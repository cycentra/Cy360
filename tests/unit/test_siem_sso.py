# 3. JWKS ENDPOINT (required by OpenSearch Security for RS256 verification)
# ─────────────────────────────────────────────────────────────────────────────

class TestJwksEndpoint:
    """
    Wazuh Dashboard's OpenSearch Security OIDC domain fetches the public key
    from /oidc/jwks to verify id_tokens. If this returns an empty key set,
    ALL CySIEM OIDC logins fail with signature verification errors.
    """

    def test_jwks_returns_200(self, client):
        resp = client.get("/oidc/jwks")
        assert resp.status_code == 200

    def test_jwks_returns_keys_array(self, client):
        resp = client.get("/oidc/jwks")
        body = json.loads(resp.data)
        assert "keys" in body, f"JWKS response missing 'keys': {body}"

    def test_jwks_key_has_required_rsa_fields_when_available(self, client):
        """When RSA is available, JWKS must contain a valid RSA JWK."""
        from blueprints.oidc import provider as oidc_prov
        if not oidc_prov._RSA_AVAILABLE:
            pytest.skip("RSA not available in this environment")

        resp = client.get("/oidc/jwks")
        body = json.loads(resp.data)
        assert len(body["keys"]) >= 1, "JWKS must contain at least one key when RSA is available"

        key = body["keys"][0]
        for field in ("kty", "use", "alg", "kid", "n", "e"):
            assert field in key, f"JWK missing required field '{field}': {key}"
        assert key["kty"] == "RSA",    f"Expected RSA key type, got {key['kty']}"
        assert key["alg"] == "RS256",  f"Expected RS256, got {key['alg']}"
        assert key["use"] == "sig",    f"Expected 'sig' use, got {key['use']}"

    def test_discovery_advertises_rs256(self, client):
        """OIDC discovery must advertise RS256 so Wazuh Dashboard configures the right alg."""
        resp = client.get("/oidc/.well-known/openid-configuration")
        assert resp.status_code == 200
        body = json.loads(resp.data)
        algs = body.get("id_token_signing_alg_values_supported", [])
        assert "RS256" in algs, (
            f"Discovery must advertise RS256 for OpenSearch Security OIDC domain: {algs}"
        )


