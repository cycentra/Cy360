class TestCySiemRS256Token:
    """
    OpenSearch Security's OIDC auth domain requires RS256 (asymmetric JWT
    verifiable via JWKS). The cysiem client must receive RS256 tokens.
    Before the fix, cysiem was in _RS256_CLIENTS but not in OIDC_CLIENTS,
    so no token was ever issued to Wazuh Dashboard.
    """

    def test_cysiem_token_exchange_returns_200(self, client, flask_app):
        """Full code→token exchange for cysiem client must succeed."""
        from core.config import OIDC_CLIENTS
        secret   = OIDC_CLIENTS["cysiem"]["client_secret"]
        code     = "test_cysiem_token_rs256"
        email    = "analyst@test.local"
        redirect = OIDC_CLIENTS["cysiem"]["redirect_uris"][0]

        _seed_auth_code(flask_app, code, "cysiem", email, redirect_uri=redirect)

        resp = client.post(
            "/oidc/token",
            data={
                "grant_type":    "authorization_code",
                "code":          code,
                "client_id":     "cysiem",
                "client_secret": secret,
            },
        )
        assert resp.status_code == 200, (
            f"cysiem OIDC token exchange failed with {resp.status_code}: {resp.data}"
        )
        body = json.loads(resp.data)
        assert "id_token"     in body, f"id_token missing: {body}"
        assert "access_token" in body, f"access_token missing: {body}"

    def test_cysiem_token_is_rs256_when_rsa_available(self, client, flask_app):
        """id_token for cysiem must use RS256 algorithm when RSA key is available."""
        from blueprints.oidc import provider as oidc_prov
        if not (oidc_prov._JWT_AVAILABLE and oidc_prov._RSA_AVAILABLE):
            pytest.skip("PyJWT or cryptography not installed — RS256 unavailable")

        from core.config import OIDC_CLIENTS
        secret   = OIDC_CLIENTS["cysiem"]["client_secret"]
        code     = "test_cysiem_token_alg"
        email    = "admin@test.local"
        redirect = OIDC_CLIENTS["cysiem"]["redirect_uris"][0]

        _seed_auth_code(flask_app, code, "cysiem", email, redirect_uri=redirect)

        resp = client.post(
            "/oidc/token",
            data={
                "grant_type":    "authorization_code",
                "code":          code,
                "client_id":     "cysiem",
                "client_secret": secret,
            },
        )
        assert resp.status_code == 200
        body = json.loads(resp.data)

        # Decode header (first segment of JWT) without verification
        header_b64 = body["id_token"].split(".")[0]
        # Re-pad: base64url strips trailing '='; (-len % 4) gives 0–3 '=' chars needed
        base64_padding = "=" * (-len(header_b64) % 4)
        header         = json.loads(base64.urlsafe_b64decode(header_b64 + base64_padding))
        assert header.get("alg") == "RS256", (
            f"cysiem id_token must use RS256 (got {header.get('alg')}). "
            "OpenSearch Security OIDC domain requires RS256 — HS256 will not verify via JWKS."
        )
        assert "kid" in header, "RS256 id_token must include a 'kid' header for JWKS lookup"

    def test_cysiem_token_contains_email_and_roles_claims(self, client, flask_app):
        """id_token must contain email, sub, and roles claims for OpenSearch role mapping."""
        from core.config import OIDC_CLIENTS
        secret   = OIDC_CLIENTS["cysiem"]["client_secret"]
        code     = "test_cysiem_token_claims"
        email    = "viewer@test.local"
        redirect = OIDC_CLIENTS["cysiem"]["redirect_uris"][0]

        _seed_auth_code(flask_app, code, "cysiem", email, redirect_uri=redirect)

        resp = client.post(
            "/oidc/token",
            data={
                "grant_type":    "authorization_code",
                "code":          code,
                "client_id":     "cysiem",
                "client_secret": secret,
            },
        )
        assert resp.status_code == 200
        body      = json.loads(resp.data)
        id_token  = body["id_token"]

        # Decode payload (second segment) without verification
        payload_b64 = id_token.split(".")[1]
        # Re-pad: base64url strips trailing '='; (-len % 4) gives 0–3 '=' chars needed
        base64_padding = "=" * (-len(payload_b64) % 4)
        payload        = json.loads(base64.urlsafe_b64decode(payload_b64 + base64_padding))

        assert payload.get("sub")   == email,   f"sub mismatch: {payload}"
        assert payload.get("email") == email,   f"email mismatch: {payload}"
        assert "roles" in payload,              f"roles claim missing: {payload}"
        assert payload.get("aud")   == "cysiem", f"aud must be 'cysiem': {payload}"

    def test_cysiem_wrong_secret_returns_401(self, client, flask_app):
        """Wrong client_secret for cysiem must be rejected."""
        code = "test_cysiem_bad_secret"
        _seed_auth_code(flask_app, code, "cysiem", "any@test.local",
                        redirect_uri="https://cysiem.cycentra.test/auth/openid/login")
        resp = client.post(
            "/oidc/token",
            data={
                "grant_type":    "authorization_code",
                "code":          code,
                "client_id":     "cysiem",
                "client_secret": "wrong-secret-value",
            },
        )
        assert resp.status_code == 401, (
            f"Expected 401 for bad cysiem secret, got {resp.status_code}"
        )


