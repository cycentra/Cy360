class TestCySiemRoleAccess:
    """
    Verify which portal roles can access which OIDC client.

    IAP gate (oauth2proxy): all portal roles — everyone who can log in to the
    portal can reach cysiem.DOMAIN through the nginx IAP.
    Wazuh Dashboard OIDC (cysiem): only admin / analyst / viewer — the SIEM-
    capable roles. cysoar role accounts do not have CySIEM access.
    """

    def _mock_role(self, email: str, role: str):
        """Return a context-manager-like that patches _load_rbac."""
        import contextlib
        from blueprints.rbac import manager as rbac_mgr

        @contextlib.contextmanager
        def _ctx():
            orig = rbac_mgr._load_rbac
            rbac_mgr._load_rbac = lambda: {email: {"role": role}}
            try:
                yield
            finally:
                rbac_mgr._load_rbac = orig

        return _ctx()

    @pytest.mark.parametrize("role", ["admin", "analyst", "viewer"])
    def test_portal_role_can_access_cysiem_oidc_client(self, role):
        """Portal SIEM roles (admin/analyst/viewer) must be allowed for cysiem client."""
        email = f"{role}@test.local"
        with self._mock_role(email, role):
            from blueprints.rbac.manager import user_can_access_client
            assert user_can_access_client(email, "cysiem"), (
                f"Role '{role}' must be permitted to use cysiem OIDC client"
            )

    @pytest.mark.parametrize("role", ["cysoar"])
    def test_non_siem_role_denied_cysiem_oidc_client(self, role):
        """Roles without CySIEM app access must NOT use cysiem OIDC client directly."""
        email = f"{role}@test.local"
        with self._mock_role(email, role):
            from blueprints.rbac.manager import user_can_access_client
            assert not user_can_access_client(email, "cysiem"), (
                f"Role '{role}' must NOT be permitted to use cysiem OIDC client directly — "
                "these roles have no CySIEM app access in ROLE_APPS"
            )

    @pytest.mark.parametrize("role", ["admin", "analyst", "viewer", "cysoar"])
    def test_all_portal_roles_can_use_oauth2proxy_iap_gate(self, role):
        """ALL portal roles must be allowed through the oauth2proxy IAP gate.

        The nginx IAP gate (oauth2proxy) should not block any logged-in portal user
        from reaching cysiem.DOMAIN — role-level filtering happens within the
        Dashboard, not at the IAP layer.
        """
        email = f"{role}@test.local"
        with self._mock_role(email, role):
            from blueprints.rbac.manager import user_can_access_client
            assert user_can_access_client(email, "oauth2proxy"), (
                f"Role '{role}' must be permitted through the oauth2proxy IAP gate "
                "— otherwise CySIEM SSO breaks for all non-admin users"
            )

    def test_unknown_user_defaults_to_viewer_and_can_access_cysiem(self):
        """Unregistered users default to 'viewer' and must be able to reach cysiem."""
        from blueprints.rbac.manager import user_can_access_client
        # 'nobody@unknown.local' has no RBAC entry — defaults to 'viewer'
        assert user_can_access_client("nobody@unknown.local", "oauth2proxy"), (
            "New/unregistered users default to viewer role and must pass the oauth2proxy gate"
        )


