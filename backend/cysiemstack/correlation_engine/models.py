class IncidentPattern(Base):
    """Phase 6: Resolved incident patterns for historical similarity scoring.

    Stored when an incident transitions to closed/resolved.  Used by
    compute_historical_similarity() to score future incidents with matching
    technique + kill-chain stage, filling the 20% historical weight slot in
    compute_investigation_confidence().
    """
    __tablename__ = "incident_patterns"

    id                        = Column(BigInteger, primary_key=True, autoincrement=True)
    source_incident_id        = Column(Text, nullable=False)
    technique                 = Column(Text, nullable=True)         # MITRE ATT&CK ID (e.g. T1059)
    kill_chain_stage          = Column(Text, nullable=True)
    process_chain             = Column(JSONB, default=list)         # correlated rule ids + names
    payload_indicators        = Column(JSONB, default=list)         # src_ips, file_paths, usernames
    response_actions          = Column(JSONB, default=dict)         # structured recommendation used
    outcome                   = Column(Text, nullable=True)         # "resolved" | "false_positive" | "closed"
    confidence_at_resolution  = Column(Numeric(4, 2), nullable=True)
    similarity_vector         = Column(JSONB, default=dict)         # pre-computed feature vector for cosine sim
    created_at                = Column(TIMESTAMP(timezone=True), default=datetime.utcnow)

    __table_args__ = (
        Index("ix_incident_patterns_technique",    "technique"),
        Index("ix_incident_patterns_kill_chain",   "kill_chain_stage"),
        Index("ix_incident_patterns_outcome",      "outcome"),
        Index("ix_incident_patterns_created_at",   "created_at"),
    )


