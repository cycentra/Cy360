async def write_audit(
    db,
    entity_type: str,
    entity_id: str,
    action: str,
    actor: str,
    from_status: str | None = None,
    to_status: str | None = None,
    comment: str | None = None,
    extra: dict | None = None,
) -> None:
    """Append an immutable audit entry to the audit_log table."""
    from datetime import datetime, timezone
    entry = AuditLog(
        entity_type = entity_type,
        entity_id   = entity_id,
        action      = action,
        actor       = actor,
        from_status = from_status,
        to_status   = to_status,
        comment     = comment,
        extra       = extra or {},
        created_at  = datetime.now(timezone.utc),
    )
    db.add(entry)


async def get_db():
    async with AsyncSessionLocal() as session:
        try:
            yield session
        finally:
            await session.close()


async def init_db():
    """Create tables if they don't exist (init.sql is primary, this is fallback)."""
    try:
        async with engine.begin() as conn:
            await conn.run_sync(Base.metadata.create_all)
            # Phase 1 migration: add ti_reputation column to existing incidents table
            await conn.execute(
                __import__("sqlalchemy").text(
                    "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS ti_reputation JSONB"
                )
            )
            # Phase 2 migration: hypothesis engine columns
            await conn.execute(
                __import__("sqlalchemy").text(
                    "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS hypotheses JSONB"
                )
            )
            await conn.execute(
                __import__("sqlalchemy").text(
                    "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS "
                    "hypothesis_generated_at TIMESTAMPTZ"
                )
            )
            # Phase 3 migration: evidence collection columns
            for col_ddl in [
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS evidence_log JSONB",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS evidence_collected_at TIMESTAMPTZ",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS evidence_coverage NUMERIC(4,2)",
            ]:
                await conn.execute(__import__("sqlalchemy").text(col_ddl))
            # Phase 4 migration: investigation confidence columns
            for col_ddl in [
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS confidence_score NUMERIC(4,2)",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS confidence_breakdown JSONB",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS confidence_computed_at TIMESTAMPTZ",
            ]:
                await conn.execute(__import__("sqlalchemy").text(col_ddl))
            # Phase 5 migration: structured recommendation + SOAR dispatch state
            for col_ddl in [
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS recommendation JSONB",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS soar_dispatched BOOLEAN DEFAULT FALSE",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS soar_dispatched_at TIMESTAMPTZ",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS soar_dispatch_log JSONB",
            ]:
                await conn.execute(__import__("sqlalchemy").text(col_ddl))
            # Phase 6 migration: incident pattern memory table
            await conn.execute(__import__("sqlalchemy").text("""
                CREATE TABLE IF NOT EXISTS incident_patterns (
                    id                       BIGSERIAL PRIMARY KEY,
                    source_incident_id       TEXT NOT NULL,
                    technique                TEXT,
                    kill_chain_stage         TEXT,
                    process_chain            JSONB DEFAULT '[]',
                    payload_indicators       JSONB DEFAULT '[]',
                    response_actions         JSONB DEFAULT '{}',
                    outcome                  TEXT,
                    confidence_at_resolution NUMERIC(4,2),
                    similarity_vector        JSONB DEFAULT '{}',
                    created_at               TIMESTAMPTZ DEFAULT NOW()
                )
            """))
            await conn.execute(__import__("sqlalchemy").text(
                "CREATE INDEX IF NOT EXISTS ix_incident_patterns_technique "
                "ON incident_patterns (technique)"
            ))
            await conn.execute(__import__("sqlalchemy").text(
                "CREATE INDEX IF NOT EXISTS ix_incident_patterns_kill_chain "
                "ON incident_patterns (kill_chain_stage)"
            ))
    except Exception as exc:
        import logging
        logging.getLogger("cysiemstack").critical(
            "DATABASE CONNECTION FAILED — check DATABASE_URL in /opt/cycentra/cysiemstack.env\n"
            "  Error: %s\n"
            "  Ensure PostgreSQL is running on 127.0.0.1:5433 and corruser has access.",
            exc,
        )
        raise
