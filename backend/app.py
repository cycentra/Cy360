"""
CyCentra 360 — Flask Backend  v4.3
====================================
This file is now a thin factory. All logic lives in blueprints/.

Blueprint → responsibility mapping:
  blueprints/auth/oauth.py       Google + Microsoft OAuth, auth verify, auth logs
  blueprints/oidc/provider.py    OIDC IdP (discovery, authorize, token, userinfo, introspect)
  blueprints/rbac/manager.py     RBAC load/save, get_user_role, user API
  blueprints/platform/routes.py  Module install / uninstall / status / logs
  blueprints/asm/scanner.py      ASM scan trigger / status / results
  blueprints/siem/proxy.py       CySIEM correlation engine proxy (13 endpoints)
  blueprints/system/routes.py    /health, /api/ai/test, /api/config
  blueprints/backup/routes.py    /api/backup/* — backup create/restore/schedule
  blueprints/audit/routes.py     /api/audit/*  — audit trail for monitoring & compliance

To add a new capability: create a new blueprint file, register it below.
To change a route: open the relevant blueprint — do not edit this file.
"""

from flask import Flask, request

from core.config import SECRET_KEY, COOKIE_SETTINGS
from core.helpers import add_cors_headers

from blueprints.auth.oauth        import auth_bp
from blueprints.oidc.provider     import oidc_bp
from blueprints.rbac.manager      import rbac_bp
from blueprints.platform.routes   import platform_bp
from blueprints.asm.scanner       import asm_bp
from blueprints.system.routes     import system_bp, reapply_o365_if_missing
from blueprints.backup.routes     import backup_bp
from blueprints.scheduler.routes  import scheduler_bp, init_scheduler
from blueprints.marketplace.routes import marketplace_bp
from blueprints.audit.routes       import audit_bp
from blueprints.sso.routes         import sso_bp
from blueprints.benchmark.routes   import benchmark_bp

# siem_proxy.py lives at backend root — import as-is (already a Blueprint)
from siem_proxy import siem_bp

# Optional: tenant validation
try:
    from tenant_manager import validate_tenant
except ImportError:
    def validate_tenant(x): return x


def create_app() -> Flask:
    app = Flask(__name__)
    app.secret_key = SECRET_KEY
    app.config.update(COOKIE_SETTINGS)

    # Register all blueprints
    for bp in (auth_bp, oidc_bp, rbac_bp, platform_bp, asm_bp, siem_bp, system_bp, backup_bp, scheduler_bp, marketplace_bp, audit_bp, sso_bp, benchmark_bp):
        app.register_blueprint(bp)

    # Start background job scheduler (only one gunicorn worker acquires lock)
    init_scheduler(app)

    # Re-inject O365 wodle if ossec.conf was reset by setup script since last save
    reapply_o365_if_missing()

    # Global CORS — applied after every response
    @app.after_request
    def _cors(response):
        return add_cors_headers(response)

    # Blanket OPTIONS handler for all /api/, /auth/, /oidc/ paths
    @app.route('/api/<path:subpath>',  methods=['OPTIONS'])
    @app.route('/auth/<path:subpath>', methods=['OPTIONS'])
    @app.route('/oidc/<path:subpath>', methods=['OPTIONS'])
    def _options(subpath):
        from flask import make_response
        return add_cors_headers(make_response('', 204))

    return app


app = create_app()

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5252, debug=False)
